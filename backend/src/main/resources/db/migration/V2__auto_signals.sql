CREATE TABLE auto_signal (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 symbol VARCHAR(20) NOT NULL,
 timeframe VARCHAR(4) NOT NULL,
 direction VARCHAR(4) NOT NULL CHECK(direction IN ('BUY','SELL')),
 status VARCHAR(12) NOT NULL,
 entry NUMERIC(20,8) NOT NULL,
 stop_loss NUMERIC(20,8) NOT NULL,
 tp1 NUMERIC(20,8) NOT NULL,
 tp2 NUMERIC(20,8) NOT NULL,
 quality INTEGER NOT NULL,
 reason VARCHAR(255) NOT NULL,
 strategy VARCHAR(40) NOT NULL,
 source_bar TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 activated_at TIMESTAMP WITH TIME ZONE,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 last_quote_at TIMESTAMP WITH TIME ZONE NOT NULL,
 tracking_gap BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(symbol,timeframe,source_bar),
 CHECK(entry>0 AND stop_loss>0 AND tp1>0 AND tp2>0),
 CHECK((direction='BUY' AND stop_loss<entry AND entry<tp1 AND tp1<tp2)
    OR (direction='SELL' AND tp2<tp1 AND tp1<entry AND entry<stop_loss))
);
CREATE INDEX auto_signal_created_idx ON auto_signal(created_at DESC);
CREATE INDEX auto_signal_tracking_idx ON auto_signal(symbol,status);
CREATE TABLE scan_state (
 id VARCHAR(60) PRIMARY KEY,
 symbol VARCHAR(20) NOT NULL,
 timeframe VARCHAR(4) NOT NULL,
 last_bar TIMESTAMP WITH TIME ZONE NOT NULL,
 last_scan_at TIMESTAMP WITH TIME ZONE NOT NULL,
 last_quote_at TIMESTAMP WITH TIME ZONE NOT NULL,
 received_at TIMESTAMP WITH TIME ZONE NOT NULL,
 reason VARCHAR(255) NOT NULL,
 quality INTEGER NOT NULL
);
