CREATE OR REPLACE FUNCTION save_signal_trade_plan() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF NEW.manual_plan_id IS NOT NULL THEN
  EXECUTE format('UPDATE %I.trade_plan SET symbol=$1,direction=$2,entry=$3,stop_loss=$4,target=$5,source_signal_id=$6 WHERE id=$7',TG_TABLE_SCHEMA)
   USING NEW.symbol,NEW.direction,NEW.entry,NEW.stop_loss,(NEW.targets->>-1)::numeric,NEW.id,NEW.manual_plan_id;
 ELSE
  EXECUTE format('INSERT INTO %I.trade_plan(symbol,direction,entry,stop_loss,target,created_at,source_signal_id) VALUES($1,$2,$3,$4,$5,$6,$7) ON CONFLICT(source_signal_id) DO NOTHING',TG_TABLE_SCHEMA)
   USING NEW.symbol,NEW.direction,NEW.entry,NEW.stop_loss,(NEW.targets->>-1)::numeric,NEW.created_at,NEW.id;
 END IF;
 RETURN NEW;
END $$;
