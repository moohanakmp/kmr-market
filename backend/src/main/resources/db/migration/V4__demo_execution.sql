CREATE TABLE broker_execution (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 signal_id BIGINT NOT NULL UNIQUE REFERENCES auto_signal(id),
 account_login BIGINT NOT NULL,
 broker_server VARCHAR(80) NOT NULL,
 worker VARCHAR(36) NOT NULL,
 status VARCHAR(20) NOT NULL,
 order_ticket BIGINT,
 position_ticket BIGINT,
 broker_stop_loss NUMERIC(20,8),
 broker_take_profit NUMERIC(20,8),
 message VARCHAR(255) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
