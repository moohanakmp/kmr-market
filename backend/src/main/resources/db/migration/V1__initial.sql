CREATE TABLE watch_item (symbol VARCHAR(20) PRIMARY KEY);
CREATE TABLE trade_plan (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 symbol VARCHAR(20) NOT NULL,
 direction VARCHAR(4) NOT NULL CHECK (direction IN ('BUY','SELL')),
 entry NUMERIC(20,8) NOT NULL CHECK(entry>0),
 stop_loss NUMERIC(20,8) NOT NULL CHECK(stop_loss>0),
 target NUMERIC(20,8) NOT NULL CHECK(target>0),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK ((direction='BUY' AND stop_loss<entry AND entry<target) OR (direction='SELL' AND target<entry AND entry<stop_loss))
);
CREATE INDEX trade_plan_created_idx ON trade_plan(created_at DESC);
